# 新しい地域区分のチェック
def check_area_v002_order(area_names, verbose = False):
    check_area_order(area_names, AREA_NAME_V002_CHECK, verbose)

# 古い地域区分のチェック
def check_area_v001_order(area_names, verbose = False):
    check_area_order(area_names, AREA_NAME_V001_CHECK, verbose)

#///////////////////////////////////////////////
# サブルーチン
# check_area_order
#
# 汎用チェック関数
# 地域名のリストをチェックする
# 長さがあわない エラー 
# 並びが一致しない エラー
#///////////////////////////////////////////////
def check_area_order(
    target_names,
    correct_names,
    verbose = False
) -> None:
    """地域名の数と並び順が定義済みフォーマットと一致するか検証する。"""

    if len(target_names) != len(correct_names):
        raise ValueError(
            f"Area length does not match: "
            f"input={len(target_names)}, "
            f"format={len(correct_names)}"
        )

    errors = []

    for i, (target, correct) in enumerate(
        zip(target_names, correct_names)
    ):
        if target != correct:
            errors.append(
                f"{i}: input={target!r}, expected={correct!r}"
            )

    if errors:
        message = "\n".join(errors)
        raise ValueError(
            f"Area format does not match:\n{message}"
        )
    elif verbose:
        print("area order check is passed.")

########################################
# フォーマット判定・DB用名称への変換
########################################

def normalize_area_names(target_names):
    """
    地域名の並びからフォーマットを判定し、
    DB用の一意な地域名を返す。
    """
    target_names = list(target_names)

    if target_names == AREA_NAME_V002_CHECK:
        return AREA_NAME_V002_COL_NAME

    if target_names == AREA_NAME_V001_CHECK:
        return AREA_NAME_V001_COL_NAME

    raise ValueError("Area does not match with any known format.")


