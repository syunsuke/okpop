########################################
# チェックして標準化した地域名列をつける
########################################
def normalize_area_name_col(df):
    """地名列をチェックして標準化"""

    if df.shape[0] == AREA_LEN_V001:
        check_area_v001_order(df["area_name"])
        df["area_name"] = AREA_NAME_V001_COL_NAME

    elif df.shape[0] == AREA_LEN_V002:
        check_area_v002_order(df["area_name"])
        df["area_name"] = AREA_NAME_V002_COL_NAME

    else:
            raise ValueError(
    "Area does not match with any known format."
            )

    return df


